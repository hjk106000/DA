'''
USER:
자연대수 e ~2.718 가 뜻하는 것이 뭐지? 
그리고 e^-x  는 수학 수식에 자꾸 나타나는데 이것이 뜻하는 것은 무었인지?


Gemini AI:
자연상수 e와 지수함수 e^-x 는 자연계의 성장과 감쇠를 설명하는 
핵심적인 수학적 개념입니다.

* 자연상수 e (≈2.718)의 의미
- 연속적인 성장 기준점: 100%의 원금이 매년 '연속적으로' 복리로 증가할 때 도달하는
  한계 성장 배율입니다.
- 수학적 정의: e = lim n→∞ (1+1/n)^n ≈ 2.71828
- 자기 자신을 복제하는 비율: e^x 라는 함수는 미분(변화율)을 해도 그대로 e^x 가 됩니다.
  즉, "현재 양에 비례해서 증가하는 현상"(인구 증가, 세포 분열, 이자 수익 등)을
  가장 자연스럽게 표현하는 기준수가 됩니다.

* $e^{-x}$가 수식에 자주 등장하는 이유
  $e^{-x}$는 지수가 음수이므로 $\frac{1}{e^x}$를 의미하며, 
  시간이나 거리가 지남에 따라 어떤 양이 지수적으로 감소(감쇠)하는 현상을 나타냅니다.
- 감쇠 및 정화 현상: 초기값에서 시작해 시간이 갈수록 0에 수렴하는 곡선을 그립니다.
- 확률 및 통계: 정규분포(가우스 분포) 곡선의 기본 뼈대가 되어 natural한 데이터 분포를 설명합니다.
- 포화 및 수렴 모델: 1-e^-x 형태로 사용되면, 초기에는 빠르게 성장하다가 
  특정 한계치에 점차 다가가는 현상(학습 곡선, 기술 수용 곡선 등)을 표현합니다.

* 실생활 응용 예시 ...

'''

import numpy as np
import matplotlib.pyplot as plt

x = np.linspace(-2, 4, 400)

y1 = np.exp(x)
y2 = np.exp(-x)
y3 = 1 - np.exp(-x)

plt.figure(figsize=(8, 5))
plt.plot(x, y1, label=r'$y = e^x$', color='blue')
plt.plot(x, y2, label=r'$y = e^{-x}$', color='red')
plt.plot(x, y3, label=r'$y = 1 - e^{-x}$', color='green')

plt.axhline(0, color='black', linewidth=0.8, linestyle='--')
plt.axvline(0, color='black', linewidth=0.8, linestyle='--')
plt.axhline(1, color='gray', linewidth=0.8, linestyle=':', label='y = 1 (Limit)')

plt.ylim(-1, 5)
plt.xlim(-2, 4)
plt.title('Comparison of Exponential Functions')
plt.legend()
plt.grid(True, alpha=0.3)
plt.show()
